<#
.SYNOPSIS
    生成 exe\VERSION 构建清单（M3-P1-7）。

.DESCRIPTION
    **为什么需要这个文件**

    `*.exe` 在 .gitignore 里，产物从不进版本控制。于是 git 里没有任何信息
    能回答"exe\ 里现在躺着的是哪一次构建"。P1-1 那次重打就撞上了这个坑：
    exe\ 里的产物停在 10-18，落后代码两个里程碑（没有 /health 端点、
    不认 HUB_PORT / HUB_DATA_DIR），而构建日志是**成功**的——
    因为那份产物根本不是这次构建的，之前的构建没有把结果搬过来。
    没人发现，因为没有任何东西会去比对。

    所以每次 build-exe.bat 成功后写一份 VERSION：commit、树是否 dirty、
    构建时间、产物清单（含大小与修改时间）。部署第一步就是核对它。

    **为什么要单独一个 .ps1 而不是写在 .bat 里**

    1) .bat 必须纯 ASCII：cmd 按控制台代码页（中文 Windows 是 cp936）读 .bat，
       非 ASCII 字节会被拆成 bogus 命令。本次就在这上面翻过一次车。
    2) 引号转义：cmd 的 `^` + PowerShell 的 `\$` 两层转义极易写错，
       而 VERSION 的内容全是引号套引号。
    3) .ps1 可以带 UTF-8 BOM（PowerShell 5.1 对无 BOM 的 .ps1 按 ANSI 解析，
       中文会连带把 \n 吃掉，报出一堆看着像真错的语法错误）。

    单独成文件后，引号只需要考虑 PowerShell 一层。

.PARAMETER ExeDir
    产物目录。默认取本脚本上级目录的 exe\。

.PARAMETER OutputFile
    输出路径。默认 <ExeDir>\VERSION。

.EXAMPLE
    .\build-version.ps1
    由 build-exe.bat 在 PyInstaller 成功后自动调用。
#>
[CmdletBinding()]
param(
    [string]$ExeDir,
    [string]$OutputFile
)

$ErrorActionPreference = 'Stop'

if (-not $ExeDir) {
    # 本脚本在 <repo>\server\ 下，产物在 <repo>\exe\
    $ExeDir = Join-Path (Split-Path -Parent $PSScriptRoot) 'exe'
}
$ExeDir = (Resolve-Path $ExeDir).Path
if (-not $OutputFile) { $OutputFile = Join-Path $ExeDir 'VERSION' }

# ---- commit 与 dirty 标记 ------------------------------------------------
$sha = (& git rev-parse --short HEAD 2>$null | Select-Object -First 1)
if (-not $sha) { $sha = 'unknown-not-a-git-repo' }

$dirtyFiles = @(& git status --porcelain 2>$null)
if ($dirtyFiles.Count) {
    $tree = "$sha-dirty-$($dirtyFiles.Count)-files-changed"
} else {
    $tree = "$sha-clean"
}

# ---- 产物清单 ------------------------------------------------------------
# 带大小与修改时间：半成品构建（比如中断后残留的旧 exe）会在这里露出来，
# 因为它的时间戳与 commit 对不上。
$arts = @()
if (Test-Path $ExeDir) {
    $arts = @(Get-ChildItem -Path $ExeDir -Filter '*.exe' -File -ErrorAction SilentlyContinue |
        Sort-Object Name | ForEach-Object {
            '{0} ({1:N0} B, {2:yyyy-MM-dd HH:mm})' -f $_.Name, $_.Length, $_.LastWriteTime
        })
}

$lines = @(
    '# LearningHub build manifest (generated by server/build-version.ps1)'
    ('# generated_at=' + (Get-Date -Format 'yyyy-MM-dd HH:mm:ss K'))
    ('commit=' + $sha)
    ('tree=' + $tree)
    ('count=' + $arts.Count)
    ('artifacts=' + ($arts -join '; '))
    '# 部署第一步：核对 commit 是否等于你期望上线的那个提交（见 docs/deploy-windows.md Step 0）'
)

Set-Content -Path $OutputFile -Value ($lines -join [Environment]::NewLine) -Encoding UTF8

Write-Host ('  commit=' + $sha + '  tree=' + $tree)
Write-Host ('  artifacts=' + $arts.Count)
if ($dirtyFiles.Count) {
    Write-Warning ("工作区有 $($dirtyFiles.Count) 处未提交改动 → tree 标记为 dirty。" +
                   "这说明这份 exe 并不对应任何一个 commit，别拿去部署。")
}